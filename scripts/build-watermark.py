#!/usr/bin/env python3
"""
Writes src/lib/watermark-glyphs.ts: the outline of the watermark text, "© Filippo Guanti", in Crimson Pro Regular
(weight 400), read from the site's own font file. Run by hand, only when the text or the font changes (the output is
committed), with the same tools as scripts/build-fonts.py:

    python -m venv .venv-fonts && .venv-fonts/bin/pip install fonttools==4.68.0 brotli
    .venv-fonts/bin/python scripts/build-watermark.py

The large version of a photograph is drawn with these outlines (src/lib/watermark.ts, decision 0043), never with a
system font, so every machine burns exactly the same mark. Advances come from the font; no kerning.
"""
from __future__ import annotations

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

TEXT = "© Filippo Guanti"
ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "public/_assets/fonts/crimson-pro.woff2"
OUT = ROOT / "src/lib/watermark-glyphs.ts"

font = TTFont(FONT)
cmap = font.getBestCmap()
glyphs = font.getGlyphSet(location={"wght": 400})
upm = font["head"].unitsPerEm
cap = font["OS/2"].sCapHeight

pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.0f}" if float(v).is_integer() else f"{v:.1f}")
x = 0
for ch in TEXT:
    name = cmap[ord(ch)]
    # Font units, y down: the baseline at y = 0, capitals reach y = -cap.
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
    x += glyphs[name].width

OUT.write_text(
    "// Generated by scripts/build-watermark.py from public/_assets/fonts/crimson-pro.woff2. Do not edit.\n"
    f"/** The outline of \"{TEXT}\" in font units (y down, baseline at 0): its advance width and cap height. */\n"
    "export const WATERMARK_GLYPHS = {\n"
    f'  text: "{TEXT}",\n'
    f"  unitsPerEm: {upm},\n"
    f"  width: {round(x)},\n"
    f"  capHeight: {cap},\n"
    f'  d: "{pen.getCommands()}",\n'
    "};\n",
    encoding="utf-8",
)
print(f"wrote {OUT.relative_to(ROOT)}: {len(TEXT)} glyphs, width {round(x)}, cap height {cap} of {upm}")
