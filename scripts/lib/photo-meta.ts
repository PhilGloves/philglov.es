/** Shared by the prebuild script, the pages and the tests. */
import type { ExifSummary } from "./photo-rights.ts";

export interface PhotoRecord {
  /** SHA-256 of the original: the cache key. */
  hash: string;
  width: number;
  height: number;
  /** Dominant colour, six lower-case hex digits. */
  colour: string;
  exif: ExifSummary;
}

/** The class that paints the image box; its rule is in photo-colours.generated.css. */
export const colourClass = (hex: string): string => `c-${hex}`;

/** One rule per distinct colour. Unlayered on purpose: it wins over the .frame and .tone-N rules. */
export function colourCss(colours: string[]): string {
  const rules = [...new Set(colours)].sort().map((c) => `.${colourClass(c)}{background:#${c}}`);
  return `/* Generated by scripts/photo-meta.ts from the originals — do not edit, never commit. */\n${rules.join("\n")}${rules.length ? "\n" : ""}`;
}
