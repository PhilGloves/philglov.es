/**
 * Runs after `astro build`. Writes dist/_headers, which Cloudflare applies to
 * the files served without the Worker (/_assets/*, robots.txt, feeds, …).
 * The headers come from the same module the Worker uses.
 *
 * SITE_ENV=production only in the production deploy; anything else (the
 * default) adds X-Robots-Tag: noindex, so a stray build is never indexable.
 */
import { writeFileSync } from "node:fs";
import { baseHeaders } from "../worker/src/headers.ts";

const env = process.env["SITE_ENV"] ?? "local";
const lines = ["# Generated by scripts/postbuild.ts — do not edit.", "/*"];
for (const [name, value] of Object.entries(baseHeaders(env))) lines.push(`  ${name}: ${value}`);

writeFileSync(new URL("../dist/_headers", import.meta.url), `${lines.join("\n")}\n`);
console.log(`postbuild: wrote dist/_headers for SITE_ENV=${env}`);
